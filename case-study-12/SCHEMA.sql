-- Case Study 12: Internship Application Tracker - Oracle XE schema
-- Run in SQLPlus / SQL Developer as user shoaib (or your app user)

CREATE TABLE applicants (
    roll_no   VARCHAR2(20) PRIMARY KEY,
    sname     VARCHAR2(100) NOT NULL,
    branch    VARCHAR2(50),
    semester  VARCHAR2(20),
    email     VARCHAR2(100),
    phone     VARCHAR2(20),
    password  VARCHAR2(50) NOT NULL,
    role      VARCHAR2(20) DEFAULT 'student'   -- 'student' or 'coordinator'
);

CREATE TABLE internships (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org         VARCHAR2(100) NOT NULL,
    role        VARCHAR2(100) NOT NULL,
    eligibility VARCHAR2(200),
    location    VARCHAR2(100),
    stipend     VARCHAR2(50),
    last_date   DATE NOT NULL
);

CREATE TABLE applications (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roll_no       VARCHAR2(20) NOT NULL,
    internship_id NUMBER NOT NULL,
    applied_date  DATE DEFAULT SYSDATE,
    status        VARCHAR2(20) DEFAULT 'Applied',   -- Applied / Shortlisted / Rejected / Selected
    remarks       VARCHAR2(300),
    CONSTRAINT fk_app_student FOREIGN KEY (roll_no) REFERENCES applicants(roll_no),
    CONSTRAINT fk_app_intern  FOREIGN KEY (internship_id) REFERENCES internships(id),
    CONSTRAINT uq_one_app UNIQUE (roll_no, internship_id)   -- prevents duplicate applications
);

